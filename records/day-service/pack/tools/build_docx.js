function phraseTable(items) {
  const rows = [new TableRow({ tableHeader: true, children: [
    cell('△ よくある書き方', PW[0], { fill: GRAY, bold: true, align: AlignmentType.CENTER }),
    cell('○ 具体的な書き方（架空の例）', PW[1], { fill: GRAY, bold: true, align: AlignmentType.CENTER })] })];
  for (const [a, b] of items) rows.push(new TableRow({ cantSplit: true, children: [cell(a, PW[0], { fill: 'F5F5F5' }), cell(b, PW[1])] }));
  return new Table({ width: { size: W, type: WidthType.DXA }, columnWidths: PW, layout: TableLayoutType.FIXED, rows });
}

